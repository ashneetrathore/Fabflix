package XMLParsing;

public class Star {
    private String id;
    private String name;
    private Integer DOB;


    public String getId() {
        return this.id;
    }

    public String getName() {
        return this.name;
    }

    public Integer getDOB() {
        return this.DOB;
    }

    public void setId(String id) { this.id = id; }

    public void setName(String name) { this.name = name; }

    public void setDOB(Integer year) { this.DOB = year; }

}